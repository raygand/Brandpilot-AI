const SUPPORTED_LANGUAGES = Object.freeze(['th', 'en', 'zh']);
const LANGUAGE_STORAGE_KEY = 'brandpilot-lang';

function normalizeLanguage(value) {
  const code = typeof value === 'string' ? value.trim().toLowerCase().split(/[-_]/)[0] : '';
  return SUPPORTED_LANGUAGES.includes(code) ? code : null;
}

function initialLanguage() {
  try {
    const saved = normalizeLanguage(globalThis.localStorage?.getItem(LANGUAGE_STORAGE_KEY));
    if (saved) return saved;
  } catch { /* Private browsing may make storage unavailable. */ }
  return normalizeLanguage(globalThis.navigator?.language) || 'th';
}

let currentLang = initialLanguage();

function resolveKey(dictionary, key) {
  if (typeof key !== 'string') return undefined;
  return key.split('.').reduce((value, part) =>
    value != null && Object.prototype.hasOwnProperty.call(value, part) ? value[part] : undefined, dictionary);
}

function t(key, replacements = {}) {
  const value = resolveKey(I18N[currentLang], key) ?? resolveKey(I18N.en, key) ?? resolveKey(I18N.th, key);
  if (value === undefined) return key;
  if (typeof value !== 'string') return value;
  // A callback treats replacement text literally, including $&, quotes and braces.
  return value.replace(/\{([^{}]+)\}/g, (token, name) =>
    Object.prototype.hasOwnProperty.call(replacements, name) ? String(replacements[name]) : token);
}

function setLanguage(language) {
  const normalized = normalizeLanguage(language);
  if (!normalized) return false;
  currentLang = normalized;
  try { globalThis.localStorage?.setItem(LANGUAGE_STORAGE_KEY, normalized); } catch { /* Continue in memory. */ }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = normalized === 'zh' ? 'zh-Hans' : normalized;
    applyTranslations(document);
  }
  return true;
}

