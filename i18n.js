    '.screen[data-screen="6"] .reflection-copy > .eyebrow': 'reflectionEyebrow',
    '.screen[data-screen="1"] .actionbar > p > b': 'transparencyLabel',
    '.screen[data-screen="2"] .actionbar > p > b': 'reflectionPromptLabel',
